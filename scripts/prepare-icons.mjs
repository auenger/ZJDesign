import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';

const css = readFileSync('node_modules/@phosphor-icons/web/src/regular/style.css', 'utf8');
const main = readFileSync('src/main.js', 'utf8') + readFileSync('src/model-lab.js', 'utf8');
const parts = readFileSync('src/parts.js', 'utf8');
const names = new Set([
  ...[...main.matchAll(/icon\('([^']+)'\)/g)].map(match => match[1]),
  ...[...parts.matchAll(/icon:\s*'([^']+)'/g)].map(match => match[1]),
  'sun', 'moon', 'speaker-high', 'speaker-slash',
]);
const rules = [...names].sort().map(name => {
  const rule = css.match(new RegExp(`\\.ph\\.ph-${name}:before\\s*\\{[^}]*\\}`));
  if (!rule) throw new Error(`Unknown icon: ${name}`);
  return rule[0];
});
mkdirSync('src/assets', { recursive: true });
copyFileSync('node_modules/@phosphor-icons/web/src/regular/Phosphor.woff2', 'src/assets/phosphor.woff2');
writeFileSync('src/icons.css', `/* Generated by scripts/prepare-icons.mjs; licensed Phosphor Icons. */
@font-face{font-family:Phosphor;src:url('./assets/phosphor.woff2') format('woff2');font-style:normal;font-weight:normal;font-display:block}
.ph{font-family:Phosphor!important;font-style:normal;font-weight:normal;line-height:1;text-transform:none;-webkit-font-smoothing:antialiased;display:inline-block}
${rules.join('\n')}
`);
console.log(`Prepared ${names.size} icons with one WOFF2 font.`);
